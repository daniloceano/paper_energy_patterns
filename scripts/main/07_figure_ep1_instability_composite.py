# Main execution
# ============================================================================

def main():
    """Generate Figure 7: EP1 instability composite (4×3)."""

    print("=" * 80)
    print("EP1 INSTABILITY COMPOSITE FIGURE (4×3)")
    print("=" * 80)

    # Check composite files
    missing = [d for d in DOMAINS if not COMPOSITE_FILES[d].exists()]
    if missing:
        print(f"\n❌ Missing composite files for: {missing}")
        print("   Run scripts/ep1_ibc_ibt_analysis/step3_precompute_composites.py first.")
        return

    # Load precomputed composites (one file per domain)
    data_dict = {}
    n_cases = None
    for domain in DOMAINS:
        print(f"\n{'='*60}")
        print(f"Loading {domain.upper()} composite")
        print(f"{'='*60}")
        data_dict[domain] = load_precomputed_composites(domain)

        # Report optional field availability
        has_pv200 = data_dict[domain]['pv_200_mean'] is not None
        has_msl   = data_dict[domain]['msl_mean']    is not None
        print(f"  PV@200={'✓' if has_pv200 else '✗ (not available)'}  "
              f"SLP={'✓' if has_msl else '✗ (not available)'}")

    print(f"\n{'='*80}")
    print("Creating figure...")
    print(f"{'='*80}")

    output_file = FIGURES_DIR / "7_ep1_instability_composite_4x3.png"
    create_main_figure(data_dict, n_cases, output_file)

    print(f"\n{'='*80}")
    print("✅ Figure 7 created successfully!")
    print(f"{'='*80}")
    print(f"\nOutput: {output_file}")
    print()


if __name__ == "__main__":
    main()
