def load_precomputed_composites(domain):
    """
    Load precomputed composite fields for a given domain from NetCDF.

    Variables read (all prefixed with domain name):
      deta_dy, deta_dy_zonal, pv_ca, pv_200, egr, msl

    Returns
    -------
    dict with keys:
      deta_dy_mean, deta_dy_zonal_mean, pv_mean, pv_200_mean,
      egr_day_mean, msl_mean, x, y, x_2d, y_2d, n_cases
    """
    nc_file = COMPOSITE_FILES[domain]
    if not nc_file.exists():
        raise FileNotFoundError(
            f"Composite file not found: {nc_file}\n"
            f"Run scripts/ep1_ibc_ibt_analysis/step3_precompute_composites.py first."
        )

    print(f"  Loading {nc_file.name} ...", flush=True)
    ds = xr.open_dataset(nc_file)

    p = f"{domain}_"  # variable name prefix

    # ---- required fields ----
    deta_dy  = ds[f"{p}deta_dy"].values        # (y, x)
    egr      = ds[f"{p}egr"].values            # (y, x)
    pv_ca    = ds[f"{p}pv_ca"].values          # (y, x)  — at Ca level (975 hPa)

    # deta_dy_zonal may be 1-D (y,) or 2-D (y, x); keep as 1-D mean
    dz_raw = ds[f"{p}deta_dy_zonal"].values
    deta_dy_zonal = dz_raw if dz_raw.ndim == 1 else dz_raw.mean(axis=-1)

    # ---- optional fields (may be absent / all-NaN) ----
    def _load_opt(name):
        key = f"{p}{name}"
        if key in ds:
            arr = ds[key].values
            return None if np.all(np.isnan(arr)) else arr
        return None

    pv_200 = _load_opt("pv_200")   # (y, x) in PVU, or None
    msl    = _load_opt("msl")      # (y, x) in Pa, or None

    # ---- use coordinates stored in the file (y is N→S: positive→negative) ----
    y_coord = f'y_{domain}'
    x_coord = f'x_{domain}'

    with xr.open_dataset(nc_file) as _ds:
        y = _ds[y_coord].values   # e.g. [+2.5 … –2.5]  (N→S)
        x = _ds[x_coord].values   # e.g. [–2.5 … +2.5]  (W→E)

    x_2d, y_2d = np.meshgrid(x, y)

    return {
        'deta_dy_mean':       deta_dy,
        'deta_dy_zonal_mean': deta_dy_zonal,
        'pv_mean':            pv_ca,
        'pv_200_mean':        pv_200,
        'egr_day_mean':       egr,
        'msl_mean':           msl,
        'x':    x,
        'y':    y,
        'x_2d': x_2d,
        'y_2d': y_2d,
    }


