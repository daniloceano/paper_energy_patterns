# Figure creation
# ============================================================================

def _ax_setup(ax, data):
    """Common axis setup: limits, aspect, grid, hide tick labels."""
    ax.set_xlim(data['x'].min(), data['x'].max())
    ax.set_ylim(data['y'].min(), data['y'].max())
    try:
        ax.set_box_aspect(1)
    except Exception:
        ax.set_aspect('equal')
    ax.grid(True, alpha=0.3, linestyle='--')
    ax.set_xticklabels([])
    ax.set_yticklabels([])


def create_main_figure(data_dict, n_cases, output_file):
    """
    Create main 4×3 composite figure.

    Rows:
      0 – RK criterion 2D map (∂η/∂y)
      1 – RK zonal-mean profile
      2 – Baroclinic PV at Ca (975 hPa, shaded) + PV@200 hPa (green contours)
      3 – EGR (shaded) + SLP (black contours)

    Columns: local (5°) | mesoscale (15°) | synoptic (30°)
    """
    fig = plt.figure(figsize=(8, 10))
    gs = gridspec.GridSpec(4, 4, hspace=0.12, wspace=0.06,
                           left=0.05, right=0.98, top=0.98, bottom=0.03,
                           width_ratios=[1, 1, 1, 0.12])

    panel_labels = [
        ['(a)', '(b)', '(c)'],
        ['(d)', '(e)', '(f)'],
        ['(g)', '(h)', '(i)'],
        ['(j)', '(k)', '(l)'],
    ]

    # -------------------------------------------------------------------------
    # Row 0 – RK 2D (∂η/∂y)
    # -------------------------------------------------------------------------
    print("  Creating Row 1: RK 2D (∂η/∂y)...")
    rk_max_abs = max(np.nanmax(np.abs(data_dict[d]['deta_dy_mean'])) for d in DOMAINS)
    levels_rk = np.linspace(-rk_max_abs, rk_max_abs, 21)

    for col, domain in enumerate(DOMAINS):
        ax = fig.add_subplot(gs[0, col])
        data = data_dict[domain]

        im = ax.contourf(data['x_2d'], data['y_2d'], data['deta_dy_mean'],
                         levels=levels_rk, cmap='RdBu_r', extend='both')
        ax.contour(data['x_2d'], data['y_2d'], data['deta_dy_mean'],
                   levels=[0], colors='k', linewidths=1.5)
        ax.plot(0, 0, 'k*', markersize=15, markeredgecolor='white', markeredgewidth=1.5)
        _ax_setup(ax, data)
        ax.text(0.01, 0.98, panel_labels[0][col], transform=ax.transAxes,
                fontsize=ANNOTATION_FONTSIZE + 1, fontweight='bold', ha='left', va='top')

        if col == 2:
            cax = fig.add_subplot(gs[0, 3])
            cb = plt.colorbar(im, cax=cax)
            cb.set_label(r'∂η/∂y (s$^{-1}$ m$^{-1}$)', fontsize=CBAR_LABELSIZE)
            cb.ax.tick_params(labelsize=CBAR_LABELSIZE)
            cb.ax.yaxis.set_major_formatter(plt.FuncFormatter(lambda x, _: f'{x:.2e}'))
            cax.yaxis.set_ticks_position('right')
            cax.xaxis.set_visible(False)

    # -------------------------------------------------------------------------
    # Row 1 – RK zonal-mean profile
    # -------------------------------------------------------------------------
    print("  Creating Row 2: RK zonal-mean...")
    for col, domain in enumerate(DOMAINS):
        ax = fig.add_subplot(gs[1, col])
        data = data_dict[domain]

        ax.axvline(0, color='k', linestyle='--', linewidth=1, alpha=0.5)
        ax.axhline(0, color='k', linestyle='-', linewidth=1, alpha=0.3)
        ax.plot(data['deta_dy_zonal_mean'], data['y'], color='b', linewidth=2.5)
        ax.set_ylim(data['y'].min(), data['y'].max())
        ax.grid(True, alpha=0.3)
        try:
            ax.set_box_aspect(1)
        except Exception:
            pass
        ax.set_xticklabels([])
        ax.set_yticklabels([])
        ax.text(0.01, 0.98, panel_labels[1][col], transform=ax.transAxes,
                fontsize=ANNOTATION_FONTSIZE + 1, fontweight='bold', ha='left', va='top')

        if col == 2:
            # Place a minimal legend in the cbar slot
            legend_ax = fig.add_subplot(gs[1, 3])
            legend_ax.axis('off')
            handles = [Line2D([0], [0], color='b', linewidth=2.5)]
            legend_ax.legend(handles, ['Composite\nmean'], loc='center',
                             frameon=True, fontsize=LEGEND_FONTSIZE, handlelength=2)

    # -------------------------------------------------------------------------
    # Row 2 – Baroclinic PV@975 hPa (shaded) + PV@200 hPa (green contours)
    # -------------------------------------------------------------------------
    print("  Creating Row 3: PV@975 + PV@200 contours...")
    pv_min = min(np.nanmin(data_dict[d]['pv_mean'] * 1e6) for d in DOMAINS)
    pv_levels = np.linspace(pv_min, 0, 21)

    for col, domain in enumerate(DOMAINS):
        ax = fig.add_subplot(gs[2, col])
        data = data_dict[domain]

        im = ax.contourf(data['x_2d'], data['y_2d'], data['pv_mean'] * 1e6,
                         levels=pv_levels, cmap='RdYlBu_r', extend='both')

        # PV@200 hPa — green contours (values already in PVU from step3)
        pv200 = data.get('pv_200_mean')
        if pv200 is not None:
            # Negative PVU contours (Southern Hemisphere: PV < 0)
            pv200_pvu = pv200 * 1e6 if np.nanmax(np.abs(pv200)) < 1e-3 else pv200
            pv200_lvls = np.linspace(np.nanmin(pv200_pvu), np.nanmax(pv200_pvu), 8)
            pv200_lvls = [v for v in pv200_lvls if v != 0]
            if pv200_lvls:
                cs200 = ax.contour(data['x_2d'], data['y_2d'], pv200_pvu,
                                   levels=pv200_lvls, colors='green',
                                   linewidths=0.9, alpha=0.8)
            # 2-PVU tropopause marker (use ±2 depending on hemisphere sign)
            trop_val = -2.0 if np.nanmean(pv200_pvu) < 0 else 2.0
            ax.contour(data['x_2d'], data['y_2d'], pv200_pvu,
                       levels=[trop_val], colors='darkgreen',
                       linewidths=2.0, linestyles='--')
        else:
            print(f"    ⚠ No PV@200 for {domain}")

        ax.plot(0, 0, 'k*', markersize=15, markeredgecolor='white', markeredgewidth=1.5)
        _ax_setup(ax, data)
        ax.text(0.01, 0.98, panel_labels[2][col], transform=ax.transAxes,
                fontsize=ANNOTATION_FONTSIZE + 1, fontweight='bold', ha='left', va='top')

        if col == 2:
            cax = fig.add_subplot(gs[2, 3])
            cb = plt.colorbar(im, cax=cax)
            cb.set_label(r'PV$_{975}$ (PVU)', fontsize=CBAR_LABELSIZE)
            cb.ax.tick_params(labelsize=CBAR_LABELSIZE)
            cb.ax.yaxis.set_major_formatter(plt.FuncFormatter(lambda x, _: f'{x:.2f}'))
            cax.yaxis.set_ticks_position('right')
            cax.xaxis.set_visible(False)

    # -------------------------------------------------------------------------
    # Row 3 – EGR (shaded) + SLP (black contours)
    # -------------------------------------------------------------------------
    print("  Creating Row 4: EGR + SLP contours...")
    egr_min_g = max(0, min(np.nanpercentile(data_dict[d]['egr_day_mean'], 1) for d in DOMAINS))
    egr_max_g = max(np.nanpercentile(data_dict[d]['egr_day_mean'], 99) for d in DOMAINS)
    egr_levels = (np.linspace(egr_min_g, egr_max_g, 21)
                  if egr_max_g > egr_min_g else np.linspace(0, 4, 21))

    for col, domain in enumerate(DOMAINS):
        ax = fig.add_subplot(gs[3, col])
        data = data_dict[domain]

        im = ax.contourf(data['x_2d'], data['y_2d'], data['egr_day_mean'],
                         levels=egr_levels, cmap='YlOrRd', extend='both')

        # SLP — black contours (values in Pa → convert to hPa)
        msl = data.get('msl_mean')
        if msl is not None:
            msl_hpa = msl / 100.0 if np.nanmean(msl) > 2000 else msl
            slp_range = np.nanmax(msl_hpa) - np.nanmin(msl_hpa)
            if slp_range > 0.5:
                slp_levels = np.arange(
                    np.floor(np.nanmin(msl_hpa) / 2) * 2,
                    np.ceil(np.nanmax(msl_hpa) / 2) * 2 + 2, 2
                )
                cs_slp = ax.contour(data['x_2d'], data['y_2d'], msl_hpa,
                                    levels=slp_levels, colors='black',
                                    linewidths=0.9, alpha=0.85)
                ax.clabel(cs_slp, fmt='%g', fontsize=8, inline=True)
        else:
            print(f"    ⚠ No SLP for {domain}")

        ax.plot(0, 0, 'k*', markersize=15, markeredgecolor='white', markeredgewidth=1.5)
        _ax_setup(ax, data)
        ax.text(0.01, 0.98, panel_labels[3][col], transform=ax.transAxes,
                fontsize=ANNOTATION_FONTSIZE + 1, fontweight='bold', ha='left', va='top')

        mean_egr = np.nanmean(data['egr_day_mean'])
        ax.text(0.98, 0.02, f'Mean: {mean_egr:.2f} day$^{{-1}}$',
                transform=ax.transAxes, fontsize=ANNOTATION_FONTSIZE,
                ha='right', va='bottom',
                bbox=dict(boxstyle='round', facecolor='white', alpha=0.8))

        if col == 2:
            cax = fig.add_subplot(gs[3, 3])
            cb = plt.colorbar(im, cax=cax)
            cb.set_label(r'EGR (day$^{-1}$)', fontsize=CBAR_LABELSIZE)
            cb.ax.tick_params(labelsize=CBAR_LABELSIZE)
            cb.ax.yaxis.set_major_formatter(plt.FuncFormatter(lambda x, _: f'{x:.2f}'))
            cax.yaxis.set_ticks_position('right')
            cax.xaxis.set_visible(False)

    # Column headers
    for col, label in enumerate(DOMAIN_LABELS):
        fig.axes[col * 1].set_title(label, fontsize=PANEL_TITLESIZE, fontweight='bold',
                                    pad=3)

    plt.savefig(output_file, dpi=DPI, bbox_inches='tight')
    plt.close()
    print(f"  ✓ Saved: {output_file.name}")


